-- =====================================================================
-- KelolaToko — skema database terpusat (satu database untuk semua modul)
-- Semua modul (Penjualan, Persediaan, Pembelian, Keuangan, SDM) membaca
-- dan menulis ke tabel yang sama sehingga data selalu konsisten.
-- Nilai uang disimpan dalam rupiah (bilangan bulat).
-- =====================================================================

-- ---------- Sistem & Pengguna ----------
CREATE TABLE IF NOT EXISTS users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  name          TEXT NOT NULL,
  role          TEXT NOT NULL CHECK (role IN ('owner','kasir','gudang','keuangan')),
  active        BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS activity_logs (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT REFERENCES users(id),
  action     TEXT NOT NULL,
  detail     TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'Asia/Jakarta', 'YYYY-MM-DD HH24:MI:SS'))
);

-- ---------- Master Data (dipakai bersama oleh semua modul) ----------
CREATE TABLE IF NOT EXISTS categories (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS suppliers (
  id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name    TEXT NOT NULL,
  phone   TEXT,
  address TEXT
);

CREATE TABLE IF NOT EXISTS customers (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         TEXT NOT NULL,
  phone        TEXT,
  address      TEXT
);

CREATE TABLE IF NOT EXISTS products (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku         TEXT NOT NULL UNIQUE,
  name        TEXT NOT NULL,
  category_id BIGINT REFERENCES categories(id),
  supplier_id BIGINT REFERENCES suppliers(id),   -- supplier utama (untuk PO otomatis)
  unit        TEXT NOT NULL DEFAULT 'pcs',
  buy_price   BIGINT NOT NULL DEFAULT 0,         -- harga beli terakhir
  sell_price  BIGINT NOT NULL DEFAULT 0,
  min_stock   BIGINT NOT NULL DEFAULT 0,         -- titik pemesanan ulang
  active      BIGINT NOT NULL DEFAULT 1
);

-- ---------- Pembelian ----------
CREATE TABLE IF NOT EXISTS purchases (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          TEXT NOT NULL UNIQUE,
  supplier_id   BIGINT NOT NULL REFERENCES suppliers(id),
  order_date    TEXT NOT NULL,
  due_date      TEXT,
  received_date TEXT,
  status        TEXT NOT NULL CHECK (status IN ('dipesan','diterima','batal')),
  total         BIGINT NOT NULL DEFAULT 0,
  paid          BIGINT NOT NULL DEFAULT 0,
  note          TEXT,
  user_id       BIGINT REFERENCES users(id),
  created_at    TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'Asia/Jakarta', 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS purchase_items (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_id BIGINT NOT NULL REFERENCES purchases(id) ON DELETE CASCADE,
  product_id  BIGINT NOT NULL REFERENCES products(id),
  qty         BIGINT NOT NULL CHECK (qty > 0),
  unit_cost   BIGINT NOT NULL CHECK (unit_cost >= 0),
  expiry_date TEXT
);

-- ---------- Persediaan ----------
-- Stok disimpan per batch agar HPP akurat dan tanggal kedaluwarsa terlacak (FEFO).
CREATE TABLE IF NOT EXISTS batches (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id    BIGINT NOT NULL REFERENCES products(id),
  purchase_id   BIGINT REFERENCES purchases(id),
  qty_in        BIGINT NOT NULL,
  qty_remaining BIGINT NOT NULL CHECK (qty_remaining >= 0),
  unit_cost     BIGINT NOT NULL,
  expiry_date   TEXT,
  received_date TEXT NOT NULL
);

-- Kartu stok: setiap perubahan stok dari modul mana pun tercatat di sini.
CREATE TABLE IF NOT EXISTS stock_movements (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date       TEXT NOT NULL,
  product_id BIGINT NOT NULL REFERENCES products(id),
  batch_id   BIGINT REFERENCES batches(id),
  type       TEXT NOT NULL,
  qty        BIGINT NOT NULL,           -- positif = masuk, negatif = keluar
  unit_cost  BIGINT NOT NULL DEFAULT 0,
  ref_type   TEXT,
  ref_id     BIGINT,
  note       TEXT,
  user_id    BIGINT REFERENCES users(id),
  created_at TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'Asia/Jakarta', 'YYYY-MM-DD HH24:MI:SS'))
);

-- ---------- Penjualan ----------
CREATE TABLE IF NOT EXISTS sales (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           TEXT NOT NULL UNIQUE,
  date           TEXT NOT NULL,
  customer_id    BIGINT REFERENCES customers(id),
  total          BIGINT NOT NULL,
  cogs           BIGINT NOT NULL DEFAULT 0,   -- HPP (dihitung dari batch FEFO)
  cash_received  BIGINT NOT NULL DEFAULT 0,
  status         TEXT NOT NULL CHECK (status IN ('selesai','batal')),
  note           TEXT,
  user_id        BIGINT REFERENCES users(id),
  created_at     TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'Asia/Jakarta', 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS sale_items (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id    BIGINT NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id),
  qty        BIGINT NOT NULL CHECK (qty > 0),
  price      BIGINT NOT NULL,
  cogs       BIGINT NOT NULL DEFAULT 0
);

-- Pembayaran hutang ke supplier
CREATE TABLE IF NOT EXISTS payments (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date       TEXT NOT NULL,
  ref_type   TEXT NOT NULL CHECK (ref_type = 'purchase'),
  ref_id     BIGINT NOT NULL,
  amount     BIGINT NOT NULL CHECK (amount > 0),
  note       TEXT,
  user_id    BIGINT REFERENCES users(id),
  created_at TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'Asia/Jakarta', 'YYYY-MM-DD HH24:MI:SS'))
);

-- ---------- Keuangan / Akuntansi ----------
CREATE TABLE IF NOT EXISTS accounts (
  code   TEXT PRIMARY KEY,
  name   TEXT NOT NULL,
  type   TEXT NOT NULL CHECK (type IN ('aset','kewajiban','modal','pendapatan','hpp','beban')),
  normal TEXT NOT NULL CHECK (normal IN ('D','K'))
);

CREATE TABLE IF NOT EXISTS journals (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date        TEXT NOT NULL,
  description TEXT NOT NULL,
  ref_type    TEXT,
  ref_id      BIGINT,
  created_at  TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'Asia/Jakarta', 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS journal_lines (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  journal_id   BIGINT NOT NULL REFERENCES journals(id) ON DELETE CASCADE,
  account_code TEXT NOT NULL REFERENCES accounts(code),
  debit        BIGINT NOT NULL DEFAULT 0,
  credit       BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS expenses (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date         TEXT NOT NULL,
  account_code TEXT NOT NULL REFERENCES accounts(code),
  amount       BIGINT NOT NULL CHECK (amount > 0),
  description  TEXT NOT NULL,
  user_id      BIGINT REFERENCES users(id),
  created_at   TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'Asia/Jakarta', 'YYYY-MM-DD HH24:MI:SS'))
);

-- ---------- SDM ----------
CREATE TABLE IF NOT EXISTS employees (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            TEXT NOT NULL,
  position        TEXT NOT NULL,
  phone           TEXT,
  base_salary     BIGINT NOT NULL DEFAULT 0,
  join_date       TEXT,
  active          BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS payrolls (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period       TEXT NOT NULL,           -- YYYY-MM
  employee_id  BIGINT NOT NULL REFERENCES employees(id),
  amount       BIGINT NOT NULL,
  paid_date    TEXT NOT NULL,
  journal_id   BIGINT REFERENCES journals(id),
  UNIQUE (period, employee_id)
);

CREATE INDEX IF NOT EXISTS idx_batches_product   ON batches(product_id, qty_remaining);
CREATE INDEX IF NOT EXISTS idx_moves_product     ON stock_movements(product_id, date);
CREATE INDEX IF NOT EXISTS idx_sales_date        ON sales(date, status);
CREATE INDEX IF NOT EXISTS idx_sale_items_prod   ON sale_items(product_id);
CREATE INDEX IF NOT EXISTS idx_journal_date      ON journals(date);
CREATE INDEX IF NOT EXISTS idx_journal_ref       ON journals(ref_type, ref_id);
CREATE INDEX IF NOT EXISTS idx_jlines_account    ON journal_lines(account_code);

-- ---------- Session login ----------
CREATE TABLE IF NOT EXISTS session (
  sid    VARCHAR NOT NULL PRIMARY KEY,
  sess   JSON NOT NULL,
  expire TIMESTAMP(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_session_expire ON session(expire);

-- ---------- Keamanan Supabase ----------
-- Aplikasi terhubung langsung sebagai pemilik tabel, jadi tidak terpengaruh.
-- Ini menutup akses dari luar lewat Data API (peran anon & authenticated).
DO $$
DECLARE t TEXT;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon, authenticated', t);
    END IF;
  END LOOP;
END $$;
